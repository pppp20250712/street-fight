function setDocsLanguage(lang) {
    if (!DOCS_I18N[lang]) return;
    localStorage.setItem('sf_docs_lang', lang);
    const d = DOCS_I18N[lang];

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        if (d[key]) {
            el.innerHTML = d[key];
        }
    });

    const selector = document.getElementById('docsLangSelect');
    if (selector) selector.value = lang;
}

function initDocsI18n() {
    let saved = localStorage.getItem('sf_docs_lang') || localStorage.getItem('sf_hyper_lang');
    if (!saved || !DOCS_I18N[saved]) {
        const nav = (navigator.language || '').toLowerCase();
        if (nav.startsWith('zh-hk') || nav.startsWith('zh-tw') || nav.startsWith('zh-hant')) saved = 'zh-Hant';
        else if (nav.startsWith('zh')) saved = 'zh-Hans';
        else if (nav.startsWith('ja')) saved = 'ja';
        else if (nav.startsWith('ko')) saved = 'ko';
        else if (nav.startsWith('th')) saved = 'th';
        else if (nav.startsWith('vi')) saved = 'vi';
        else if (nav.startsWith('id')) saved = 'id';
        else if (nav.startsWith('ms')) saved = 'ms';
        else if (nav.startsWith('fil') || nav.startsWith('tl')) saved = 'fil';
        else if (nav.startsWith('hi')) saved = 'hi';
        else saved = 'en';
    }
    setDocsLanguage(saved);
}

window.addEventListener('DOMContentLoaded', initDocsI18n);
